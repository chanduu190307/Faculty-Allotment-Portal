  /**
   * Generates Excel workbook buffer for Daily Report.
   */
  public static async generateDailyReportExcel(report: DailyReportSnapshot): Promise<Buffer> {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Faculty Allotment System';
    workbook.created = new Date();

    const sheet = workbook.addWorksheet('Daily Allotment Report');

    // Title & Metadata
    sheet.addRow([report.collegeName]);
    sheet.addRow([`DAILY EXAMINATION ALLOTMENT REPORT - ${report.examinationName} (${report.academicYear})`]);
    sheet.addRow([`Date: ${report.date}`, `Status: ${report.isProvisional ? 'PROVISIONAL' : 'FINAL'}`, `Report ID: ${report.reportId}`]);
    sheet.addRow([]);

    // Table Header
    const headerRow = sheet.addRow([
      'Session',
      'Room ID',
      'Room Name',
      'Building / Block',
      'Faculty ID',
      'Faculty Name',
      'Department',
      'Designation',
      'Duty Status',
    ]);

    headerRow.font = { bold: true };
    headerRow.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FFE2E0D7' },
    };

    for (const a of report.roomAssignments) {
      sheet.addRow([
        a.session,
        a.room_id,
        a.room_name,
        a.building,
        a.faculty_id,
        a.faculty_name,
        a.department,
        a.designation,
        a.status,
      ]);
    }

    // Auto-fit column widths
    sheet.columns.forEach((col) => {
      let maxLen = 12;
      col.eachCell?.({ includeEmpty: false }, (cell) => {
        const val = cell.value ? cell.value.toString() : '';
        if (val.length > maxLen) maxLen = Math.min(val.length + 2, 40);
      });
      col.width = maxLen;
    });

    const buffer = await workbook.xlsx.writeBuffer();
    return Buffer.from(buffer);
  }

  /**
   * Generates PDF buffer for Daily Report.
   */
  public static generateDailyReportPDF(report: DailyReportSnapshot): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({ margin: 40, size: 'A4' });
        const chunks: Buffer[] = [];

        doc.on('data', (chunk) => chunks.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(chunks)));
        doc.on('error', (err) => reject(err));

        // Header
        doc.fontSize(16).text(report.collegeName, { align: 'center' });
        doc.fontSize(12).text(`DAILY EXAMINATION ALLOTMENT REPORT`, { align: 'center' });
        doc.fontSize(10).text(`${report.examinationName} (${report.academicYear})`, { align: 'center' });
        doc.moveDown(0.5);

        doc.fontSize(9).text(`Date: ${report.date} | Version: V${report.reportVersion} (${report.isProvisional ? 'PROVISIONAL' : 'APPROVED FINAL'})`, { align: 'center' });
        doc.moveDown(0.5);

        doc.moveTo(40, doc.y).lineTo(555, doc.y).strokeColor('#879B83').stroke();
        doc.moveDown(1);

        // Summary Statistics Box
        doc.fontSize(10).fillColor('#242923').text(`Summary Overview:`, { underline: true });
        doc.fontSize(9).text(`Total Active Rooms: ${report.summary.totalRooms} | Total Duties: ${report.summary.totalAssignments}`);
        doc.text(`Completed: ${report.summary.completedCount} | Absent: ${report.summary.absentCount} | Substituted: ${report.summary.substitutedCount}`);
        doc.moveDown(1);

        // Assignments Table
        doc.fontSize(10).text(`Room-wise Duty Assignments:`, { underline: true });
        doc.moveDown(0.5);

        // Print assignments
        doc.fontSize(8);
        for (const a of report.roomAssignments) {
          const line = `[${a.session}] Room ${a.room_id} (${a.building}): ${a.faculty_name} (${a.faculty_id}, ${a.department}) — Status: ${a.status}`;
          doc.text(line);
          if (doc.y > 750) {
            doc.addPage();
          }
        }

        // Footer signatures
        if (doc.y > 700) doc.addPage();
        doc.moveDown(2);
        doc.fontSize(9).text(`Generated By: ${report.generatedBy} on ${new Date(report.generatedAt).toLocaleString()}`);
        doc.text(`Approved By: ${report.approvedBy || 'Pending Official Approval'}`);
        doc.text(`Examination Officer Signature`);

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }

